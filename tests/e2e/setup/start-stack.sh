#!/usr/bin/env bash
# Start the end-to-end test stack (production image + MySQL + Mailpit), prepare
# the database and create the test accounts (two administrators, one user).
#
#   tests/e2e/setup/start-stack.sh
#
# Environment (all optional):
#   E2E_PROJECT       Docker Compose project name (default: lvcs-e2e)
#   E2E_APP_PORT      host port for the app, bound to 127.0.0.1 (default: 8080; the Docker test runner needs 8080)
#   E2E_MAILPIT_PORT  host port for the Mailpit inbox and API (default: 8125)
#   E2E_IMAGE         image tag for the app (default: lvcs-e2e:local)
#   E2E_SKIP_BUILD=1  use an already built E2E_IMAGE instead of building it
#
# Every secret (APP_KEY, database passwords, account passwords) is random and
# generated on each run. They are written to tests/e2e/.stack/stack.env
# (gitignored, mode 600), which Playwright and the other scripts read.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
STATE_DIR="$ROOT/tests/e2e/.stack"
STATE_FILE="$STATE_DIR/stack.env"

E2E_PROJECT="${E2E_PROJECT:-lvcs-e2e}"
E2E_APP_PORT="${E2E_APP_PORT:-8080}"
E2E_MAILPIT_PORT="${E2E_MAILPIT_PORT:-8125}"
E2E_IMAGE="${E2E_IMAGE:-lvcs-e2e:local}"

random_hex() { openssl rand -hex "$1"; }

# Remove state from an earlier run first, so it is never sent to the Docker
# build context and stale credentials are never reused.
rm -rf "$STATE_DIR"

if [ "${E2E_SKIP_BUILD:-}" != "1" ]; then
    echo "Building the production image ($E2E_IMAGE)..."
    docker build -f "$ROOT/docker/Dockerfile" --target prod -t "$E2E_IMAGE" "$ROOT"
fi

mkdir -p "$STATE_DIR"
chmod 700 "$STATE_DIR"
umask 077
cat > "$STATE_FILE" <<EOF
# Generated by tests/e2e/setup/start-stack.sh. Throwaway values for the
# local end-to-end stack only. Deleted by stop-stack.sh.
E2E_PROJECT=$E2E_PROJECT
E2E_IMAGE=$E2E_IMAGE
E2E_APP_PORT=$E2E_APP_PORT
E2E_MAILPIT_PORT=$E2E_MAILPIT_PORT
E2E_UID=$(id -u)
E2E_GID=$(id -g)
E2E_BASE_URL=http://localhost:$E2E_APP_PORT
E2E_MAILPIT_URL=http://localhost:$E2E_MAILPIT_PORT
E2E_APP_KEY=base64:$(openssl rand -base64 32)
E2E_DB_PASSWORD=$(random_hex 24)
E2E_DB_ROOT_PASSWORD=$(random_hex 24)
E2E_ADMIN_NAME="Demo Admin"
E2E_ADMIN_EMAIL=admin@example.test
E2E_ADMIN_PASSWORD=$(random_hex 16)
E2E_ADMIN2_NAME="Second Admin"
E2E_ADMIN2_EMAIL=admin2@example.test
E2E_ADMIN2_PASSWORD=$(random_hex 16)
E2E_USER_NAME="Demo User"
E2E_USER_EMAIL=user@example.test
E2E_USER_PASSWORD=$(random_hex 16)
EOF
umask 022

compose() {
    docker compose -p "$E2E_PROJECT" -f "$ROOT/tests/e2e/compose.yaml" --env-file "$STATE_FILE" "$@"
}

echo "Starting the stack (project $E2E_PROJECT)..."
compose up -d --wait --wait-timeout 180 db mailpit app

artisan() {
    compose exec -T app php artisan "$@"
}

artisan migrate --force --no-interaction
artisan passport:keys --force --no-interaction
artisan passport:client --personal --no-interaction
artisan db:seed --force --no-interaction

# app:create-admin is interactive by design, so the test accounts are created
# with tinker. The values are passed as environment variables (names only on
# the command line), never as arguments.
set -a
# shellcheck disable=SC1090
. "$STATE_FILE"
set +a
# The PHP code is single-quoted on purpose: $user and $prefix are PHP variables.
# shellcheck disable=SC2016
compose exec -T -e HOME=/tmp \
    -e E2E_ADMIN_NAME -e E2E_ADMIN_EMAIL -e E2E_ADMIN_PASSWORD \
    -e E2E_ADMIN2_NAME -e E2E_ADMIN2_EMAIL -e E2E_ADMIN2_PASSWORD \
    -e E2E_USER_NAME -e E2E_USER_EMAIL -e E2E_USER_PASSWORD \
    app php artisan tinker --no-interaction --execute '
foreach (["E2E_ADMIN" => "admin", "E2E_ADMIN2" => "admin", "E2E_USER" => "user"] as $prefix => $type) {
    $user = App\Models\User::firstOrNew(["email" => getenv("{$prefix}_EMAIL")]);
    $user->name = getenv("{$prefix}_NAME");
    $user->password = getenv("{$prefix}_PASSWORD");
    $user->forceFill(["type" => $type, "email_verified_at" => now()])->save();
}
echo "Test accounts ready.", PHP_EOL;
'

echo "E2E stack is up: app http://localhost:$E2E_APP_PORT, Mailpit http://localhost:$E2E_MAILPIT_PORT"
